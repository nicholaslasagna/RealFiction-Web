package com.realfiction.realcore.lobby.seasonal;

/** Minimal 5x7 particle bitmap font for sky banners. */
public final class ParticleBitmapFont {
  @FunctionalInterface
  public interface PixelVisitor {
    void visit(int column, int row);
  }

  private static final int[][] GLYPHS = new int[128][];

  static {
    define(' ', 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00);
    define('0', 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E);
    define('2', 0x0E, 0x11, 0x02, 0x04, 0x08, 0x10, 0x1F);
    define('5', 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E);
    define('A', 0x04, 0x0A, 0x11, 0x11, 0x1F, 0x11, 0x11);
    define('C', 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E);
    define('E', 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F);
    define('F', 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10);
    define('H', 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11);
    define('I', 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E);
    define('L', 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F);
    define('M', 0x11, 0x1B, 0x15, 0x11, 0x11, 0x11, 0x11);
    define('N', 0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11);
    define('O', 0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E);
    define('R', 0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11);
    define('S', 0x0E, 0x11, 0x10, 0x0E, 0x01, 0x11, 0x0E);
    define('T', 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04);
    define('U', 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E);
    define('Y', 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04);
  }

  private ParticleBitmapFont() {
  }

  public static int textWidth(String text) {
    if (text == null || text.isEmpty()) {
      return 0;
    }
    int width = 0;
    for (int i = 0; i < text.length(); i++) {
      width += 6;
    }
    return Math.max(0, width - 1);
  }

  public static void forEachPixel(String text, PixelVisitor visitor) {
    if (text == null || text.isEmpty()) {
      return;
    }
    int column = 0;
    for (int i = 0; i < text.length(); i++) {
      int[] glyph = GLYPHS[Character.toUpperCase(text.charAt(i))];
      if (glyph == null) {
        column += 6;
        continue;
      }
      for (int row = 0; row < 7; row++) {
        int bits = glyph[row];
        for (int bit = 0; bit < 5; bit++) {
          if (((bits >> (4 - bit)) & 1) == 1) {
            visitor.visit(column + bit, row);
          }
        }
      }
      column += 6;
    }
  }

  private static void define(char ch, int... rows) {
    GLYPHS[ch] = rows;
  }
}
